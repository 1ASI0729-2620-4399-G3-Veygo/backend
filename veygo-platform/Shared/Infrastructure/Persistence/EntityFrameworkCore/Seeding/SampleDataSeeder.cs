using BookingAggregate = Veygo.Platform.Booking.Domain.Model.Aggregates.Booking;
using NotificationAggregate = Veygo.Platform.Notification.Domain.Model.Aggregates.Notification;

namespace Veygo.Platform.Shared.Infrastructure.Persistence.EntityFrameworkCore.Seeding;

/// <summary>
///     Loads the sample data of the web application (the former json-server <c>db.json</c>, without users)
///     into an empty database, so the platform can be demoed right away.
/// </summary>
/// <remarks>
///     Every record is created through the domain model (constructors and behavior methods), and the ids of
///     the file are mapped to the ids generated by MySQL. User ids (owners and renters) are kept as they are,
///     because users still live in the IAM fake API until the IAM bounded context is implemented.
/// </remarks>
public class SampleDataSeeder(AppDbContext context, ILogger<SampleDataSeeder> logger)
{
    private static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web);

    /// <summary>
    ///     Seeds the database when it has no vehicles yet.
    /// </summary>
    /// <param name="sampleDataPath">Path of the sample data JSON file.</param>
    /// <param name="cancellationToken">The cancellation token.</param>
    public async Task SeedAsync(string sampleDataPath, CancellationToken cancellationToken = default)
    {
        if (await context.Set<Vehicle>().AnyAsync(cancellationToken))
        {
            logger.LogInformation("Sample data skipped: the database already has vehicles.");
            return;
        }

        if (!File.Exists(sampleDataPath))
        {
            logger.LogWarning("Sample data skipped: file {Path} not found.", sampleDataPath);
            return;
        }

        await using var stream = File.OpenRead(sampleDataPath);
        var data = await JsonSerializer.DeserializeAsync<SampleData>(stream, JsonOptions, cancellationToken)
                   ?? throw new InvalidOperationException("The sample data file is empty.");

        // 1. Fleet: vehicles
        var vehicles = new Dictionary<int, Vehicle>();
        foreach (var item in data.Vehicles)
        {
            var resource = item.Deserialize<CreateVehicleResource>(JsonOptions)!;
            var summary = item.Deserialize<SampleVehicleSummary>(JsonOptions)!;
            var vehicle = new Vehicle(VehicleCommandFromResourceAssembler.ToCreateCommandFromResource(resource));
            vehicle.UpdateReputation(summary.Rating, summary.ReviewsCount);
            vehicles[summary.Id] = vehicle;
            context.Add(vehicle);
        }

        await context.SaveChangesAsync(cancellationToken);

        // 2. Fleet: blocked dates / Booking: bookings
        foreach (var item in data.BlockedDates.Where(item => vehicles.ContainsKey(item.VehicleId)))
            context.Add(new BlockedDate(new CreateBlockedDateCommand(vehicles[item.VehicleId].Id,
                DateValueAssembler.ToDate(item.Date, "date"))));

        var bookings = new Dictionary<int, BookingAggregate>();
        foreach (var item in data.Bookings.Where(item => vehicles.ContainsKey(item.VehicleId)))
        {
            var vehicle = vehicles[item.VehicleId];
            var startDate = DateValueAssembler.ToDate(item.StartDate, "startDate");
            var command = new CreateBookingCommand(vehicle.Id, item.RenterId, startDate,
                DateValueAssembler.ToDate(item.EndDate, "endDate"),
                EnumValueAssembler.ToEnum<EPaymentMethod>(item.PaymentMethod, "paymentMethod"));
            var booking = new BookingAggregate(command,
                new VehicleRentalTerms(vehicle.Id, vehicle.OwnerId, item.PricePerDay, true)) { CreatedAt = item.CreatedAt };

            var status = EnumValueAssembler.ToEnum<EBookingStatus>(item.Status, "status");
            var confirmedAt = item.ConfirmedAt ?? item.CreatedAt;
            if (status is EBookingStatus.Confirmed or EBookingStatus.Completed ||
                (status == EBookingStatus.Cancelled && item.ConfirmedAt.HasValue))
                booking.ChangeStatus(EBookingStatus.Confirmed, startDate, confirmedAt);
            if (status != EBookingStatus.Pending && status != EBookingStatus.Confirmed)
                booking.ChangeStatus(status, startDate, confirmedAt);
            booking.ClearDomainEvents();

            bookings[item.Id] = booking;
            context.Add(booking);
        }

        await context.SaveChangesAsync(cancellationToken);

        // 3. Reputation: reviews / Engagement: favorites / Communication: conversations
        foreach (var item in data.Reviews.Where(item => bookings.ContainsKey(item.BookingId)))
        {
            var booking = bookings[item.BookingId];
            var summary = new BookingSummary(booking.Id, booking.VehicleId, booking.OwnerId, booking.RenterId, true);
            context.Add(new Review(new CreateReviewCommand(booking.Id, booking.RenterId, item.Rating, item.Comment ?? ""),
                summary) { CreatedAt = item.CreatedAt });
        }

        foreach (var item in data.Favorites.Where(item => vehicles.ContainsKey(item.VehicleId)))
            context.Add(new Favorite(new CreateFavoriteCommand(item.RenterId, vehicles[item.VehicleId].Id))
                { CreatedAt = item.CreatedAt });

        var conversations = new Dictionary<int, Conversation>();
        foreach (var item in data.Conversations)
        {
            int? vehicleId = item.VehicleId.HasValue && vehicles.TryGetValue(item.VehicleId.Value, out var vehicle)
                ? vehicle.Id
                : null;
            var conversation = new Conversation(new CreateConversationCommand(item.RenterId, item.OwnerId, vehicleId))
                { CreatedAt = item.CreatedAt };
            if (!string.IsNullOrWhiteSpace(item.LastMessagePreview))
                conversation.RecordMessage(item.LastMessagePreview, item.LastMessageAt ?? item.CreatedAt);
            conversations[item.Id] = conversation;
            context.Add(conversation);
        }

        await context.SaveChangesAsync(cancellationToken);

        // 4. Communication: messages / Notification: notifications
        foreach (var item in data.Messages.Where(item => conversations.ContainsKey(item.ConversationId)))
        {
            var message = new Message(new CreateMessageCommand(conversations[item.ConversationId].Id, item.SenderId,
                item.Content)) { CreatedAt = item.SentAt };
            if (item.Read) message.MarkAsRead();
            context.Add(message);
        }

        foreach (var item in data.Notifications)
        {
            var notification = new NotificationAggregate(new CreateNotificationCommand(item.UserId,
                EnumValueAssembler.ToEnum<ENotificationType>(item.Type, "type"),
                item.Params?.GetRawText(), item.Link?.GetRawText())) { CreatedAt = item.CreatedAt };
            if (item.Read) notification.MarkAsRead();
            context.Add(notification);
        }

        await context.SaveChangesAsync(cancellationToken);
        logger.LogInformation(
            "Sample data loaded: {Vehicles} vehicles, {Bookings} bookings, {Conversations} conversations.",
            vehicles.Count, bookings.Count, conversations.Count);
    }

    private record SampleData(
        List<JsonElement> Vehicles,
        List<SampleBlockedDate> BlockedDates,
        List<SampleBooking> Bookings,
        List<SampleReview> Reviews,
        List<SampleFavorite> Favorites,
        List<SampleConversation> Conversations,
        List<SampleMessage> Messages,
        List<SampleNotification> Notifications);

    private record SampleVehicleSummary(int Id, double Rating, int ReviewsCount);

    private record SampleBlockedDate(int VehicleId, string Date);

    private record SampleBooking(
        int Id,
        int VehicleId,
        int RenterId,
        string StartDate,
        string EndDate,
        decimal PricePerDay,
        string Status,
        string PaymentMethod,
        DateTimeOffset CreatedAt,
        DateTimeOffset? ConfirmedAt);

    private record SampleReview(int BookingId, int Rating, string? Comment, DateTimeOffset CreatedAt);

    private record SampleFavorite(int RenterId, int VehicleId, DateTimeOffset CreatedAt);

    private record SampleConversation(
        int Id,
        int RenterId,
        int OwnerId,
        int? VehicleId,
        DateTimeOffset CreatedAt,
        DateTimeOffset? LastMessageAt,
        string? LastMessagePreview);

    private record SampleMessage(int ConversationId, int SenderId, string Content, DateTimeOffset SentAt, bool Read);

    private record SampleNotification(
        int UserId,
        string Type,
        JsonElement? Params,
        JsonElement? Link,
        bool Read,
        DateTimeOffset CreatedAt);
}
